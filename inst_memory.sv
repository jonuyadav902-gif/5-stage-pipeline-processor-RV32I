module inst_memory(

    input  logic [31:0] A,
    output logic [31:0] RD

);

always_comb begin

    case(A[11:2])

    // =====================================================
    // BASIC VALUES
    // =====================================================

    10'd0  : RD = 32'h00500093; // addi x1,x0,5
    10'd1  : RD = 32'h00A00113; // addi x2,x0,10
    10'd2  : RD = 32'hFFD00193; // addi x3,x0,-3

    // =====================================================
    // R-TYPE
    // =====================================================

    10'd3  : RD = 32'h00208233; // add x4,x1,x2
    10'd4  : RD = 32'h401102B3; // sub x5,x2,x1
    10'd5  : RD = 32'h0020F333; // and x6,x1,x2
    10'd6  : RD = 32'h0020E3B3; // or x7,x1,x2
    10'd7  : RD = 32'h0020C433; // xor x8,x1,x2
    10'd8  : RD = 32'h002094B3; // sll x9,x1,x2
    10'd9  : RD = 32'h00115533; // srl x10,x2,x1
    10'd10 : RD = 32'h4011D5B3; // sra x11,x3,x1
    10'd11 : RD = 32'h0020A633; // slt x12,x1,x2
    10'd12 : RD = 32'h001136B3; // sltu x13,x2,x1

    // =====================================================
    // I-TYPE
    // =====================================================

    10'd13 : RD = 32'h00708713; // addi x14,x1,7
    10'd14 : RD = 32'h0030E793; // ori x15,x1,3
    10'd15 : RD = 32'h0010F813; // andi x16,x1,1
    10'd16 : RD = 32'h00F0C893; // xori x17,x1,15
    10'd17 : RD = 32'h00209913; // slli x18,x1,2
    10'd18 : RD = 32'h00115993; // srli x19,x2,1
    10'd19 : RD = 32'h4011DA13; // srai x20,x3,1
    10'd20 : RD = 32'h00A0AA93; // slti x21,x1,10
    10'd21 : RD = 32'h00113B13; // sltiu x22,x2,1

    // =====================================================
    // STORE TEST
    // =====================================================

    10'd22 : RD = 32'h06100A23; // sb x1,116(x0)
    10'd23 : RD = 32'h06201C23; // sh x2,120(x0)
    10'd24 : RD = 32'h06402E23; // sw x4,124(x0)

    // =====================================================
    // LOAD TEST
    // =====================================================

    10'd25 : RD = 32'h07400B83; // lb x23,116(x0)
    10'd26 : RD = 32'h07801C03; // lh x24,120(x0)
    10'd27 : RD = 32'h07C02C83; // lw x25,124(x0)
    10'd28 : RD = 32'h07404D03; // lbu x26,116(x0)
    10'd29 : RD = 32'h07805D83; // lhu x27,120(x0)

    // =====================================================
    // BRANCH TESTS
    // =====================================================

    10'd30 : RD = 32'h00208463; // beq x1,x2,+8
    10'd31 : RD = 32'h00100E13; // addi x28,x0,1

    10'd32 : RD = 32'h00209463; // bne x1,x2,+8
    10'd33 : RD = 32'h00200E13; // addi x28,x0,2

    10'd34 : RD = 32'h0020C463; // blt x1,x2,+8
    10'd35 : RD = 32'h00300E13; // addi x28,x0,3

    10'd36 : RD = 32'h00115463; // bge x2,x1,+8
    10'd37 : RD = 32'h00400E13; // addi x28,x0,4

    // =====================================================
